import assert from "node:assert/strict";
import { test } from "node:test";
import { candidateProse, checkContentLanguage, clearlyEnglishProse, contentLanguagePolicy, issueProse, requirementProse, verificationProse } from "../src/content-language.js";
import type { CandidateSubmissionV2Input, IssueInput, RequirementInput, VerificationReportInput } from "../src/domain.js";
import { LedgerFixture } from "./fixture.js";

const policy = contentLanguagePolicy("zh-CN", undefined);

test("Chinese content policy flags prose while preserving code, paths, and raw evidence", () => {
  assert.equal(clearlyEnglishProse("Present the full Grounds identity on sufficiently large root homes"), true);
  assert.equal(clearlyEnglishProse("使用 `BrandIdentity` 在 94×28 终端显示完整标识，保留 `NO_COLOR` 行为。"), false);
  assert.equal(clearlyEnglishProse("`Present the full Grounds identity on sufficiently large root homes`"), false);
  assert.equal(clearlyEnglishProse("执行 npm test 并记录结果"), false);
  const requirement: RequirementInput = { format: 1, summary: "实现中文审阅", outcomes: ["读者能看到中文验收结论"], decisions: [{ statement: "默认使用中文", options: [{ key: "english", description: "Write every review statement in English for all readers" }], chosen_option: "english" }] };
  const issue: IssueInput = { format: 1, summary: "调整审阅", goals: [{ statement: "审阅更清晰", criteria: ["The supporting copy does not repeat Grounds below the wordmark"] }] };
  assert.throws(() => checkContentLanguage([...requirementProse(requirement), ...issueProse(issue)], policy), (error: any) =>
    error.code === "VALIDATION_ERROR" && /decisions\[0\]\.options\[0\]\.description/.test(error.details.reason) && /goals\[0\]\.criteria\[0\]/.test(error.details.reason));
  assert.throws(() => checkContentLanguage([
    { path: "issue.goals[0]", value: "Search behavior" },
    { path: "issue.goals[1]", value: "Navigation behavior" },
    { path: "issue.goals[2]", value: "Responsive presentation" },
  ], policy), (error: any) => error.details.reason.includes("issue.goals[2]"));
});

test("candidate and verifier prose is checked without inspecting evidence payloads", () => {
  const candidate: CandidateSubmissionV2Input = {
    format: "patchledger.candidate-submission/v2", explanation: "完成中文界面", change_index: { format: "patchledger.change-index/v1", patch_digest: "x", units_digest: "y" },
    claims: [{ target_type: "goal", target_id: "goal", explanation: "实现了目标", criteria: [{ criterion_id: "criterion", explanation: "完成实现", self_verification: { status: "satisfied", explanation: "测试通过", method: "运行 `npm test`" }, evidence: [{ type: "command", command: "npm test", exit_code: 0, output: "This is a long English test output generated by the test runner" }] }] }],
    change_rationales: [{ change_refs: ["change"], relation: "implements", target_refs: [{ type: "criterion", id: "criterion" }], rationale: "This code change adds a new layout and preserves the old behavior", alternatives: [], risks: [] }],
  };
  assert.throws(() => checkContentLanguage(candidateProse(candidate), policy), (error: any) => error.details.reason.includes("change_rationales[0].rationale"));
  candidate.change_rationales[0].rationale = "调整布局并保留旧行为";
  assert.deepEqual(checkContentLanguage(candidateProse(candidate), policy), []);

  const report: VerificationReportInput = { format: "patchledger.verification-report/v1", candidate_id: "id", result_tree_oid: "oid", blind_context_digest: "digest", assessments: [{ target_type: "goal", target_id: "goal", criteria: [{ criterion_id: "criterion", independent: { verdict: "qualified", explanation: "The rendered home preserves the existing search and navigation behavior", evidence: [{ type: "observation", statement: "English output from a tool", attribution: { kind: "agent", agent_id: "a", display_name: "a" } }] }, reconciliation: { claim_relation: "corroborated", explanation: "与作者声明一致" }, final: { verdict: "qualified", explanation: "满足" } }] }] };
  assert.throws(() => checkContentLanguage(verificationProse(report), policy), (error: any) => error.details.reason.includes("independent.explanation"));
  report.assessments[0].criteria[0].independent.explanation = "主页保持既有搜索和导航行为";
  assert.deepEqual(checkContentLanguage(verificationProse(report), policy), []);
});

test("language override requires a reason and returns a visible warning", () => {
  assert.throws(() => contentLanguagePolicy(undefined, "because"), { code: "VALIDATION_ERROR" });
  assert.throws(() => contentLanguagePolicy("en-US", undefined), { code: "VALIDATION_ERROR" });
  assert.throws(() => contentLanguagePolicy("zh-CN", "  "), { code: "VALIDATION_ERROR" });
  const warnings = checkContentLanguage([{ path: "requirement.summary", value: "Present the full Grounds identity" }], contentLanguagePolicy("zh-CN", "引用上游原文"));
  assert.equal(warnings[0].code, "CONTENT_LANGUAGE_OVERRIDE");
  assert.match(warnings[0].message, /引用上游原文/);
  assert.deepEqual(checkContentLanguage([{ path: "requirement.summary", value: "Present the full Grounds identity" }], undefined), []);
});

test("Chinese Candidate and Verification templates keep IDs while localizing prose placeholders", async () => {
  const fixture = await LedgerFixture.create();
  try {
    const candidate = await fixture.submitCandidate();
    const draft = await fixture.module.candidateSubmissionTemplate(candidate.run.context.dev_run.id, candidate.artifact, "zh-CN");
    assert.match(draft.submission.explanation, /用中文/);
    assert.match(draft.submission.claims[0].criteria[0].explanation, /用中文/);
    assert.equal(draft.submission.claims[0].criteria[0].criterion_id, candidate.criterion_id);
    const verification = await fixture.module.verificationReportTemplate(candidate.candidate.candidate_id, "zh-CN");
    assert.match(verification.report.assessments[0].criteria[0].independent.explanation, /用中文/);
    assert.equal(verification.report.assessments[0].criteria[0].criterion_id, candidate.criterion_id);
  } finally { await fixture.close(); }
});
